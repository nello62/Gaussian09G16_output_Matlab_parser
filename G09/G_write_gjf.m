function G_write_gjf(outFile, symbols, xyz, route, charge, mult, varargin)
%G_WRITE_GJF  Writes a Gaussian 09/16 input file (.gjf) from an in-memory
%   molecule and job specification.
%
%   G_WRITE_GJF(outFile, symbols, xyz, route, charge, mult)
%   G_WRITE_GJF(..., Name, Value, ...)
%
%   Input:
%       outFile  - output .gjf path
%       symbols  - {Natoms x 1 cell} atomic symbols
%       xyz      - [Natoms x 3 double] Cartesian coordinates (Angstrom)
%       route    - char, the full route line, e.g. '# opt freq b3lyp/6-31g(d)'
%       charge   - int, total molecular charge
%       mult     - int, spin multiplicity
%
%   Optional parameters (Name-Value):
%       'Title'      - title/comment line (default: 'Generated by G_write_gjf')
%       'Chk'        - %chk Link0 value (default: '', line omitted if empty)
%       'Mem'        - %mem Link0 value (default: '', line omitted if empty)
%       'Nproc'      - %nprocshared Link0 value (default: 0, line omitted if <= 0)
%       'BasisBlock' - char, a gen/genecp basis-set (and, if present, ECP)
%                      text block written verbatim after the molecule
%                      specification, terminated by a blank line (default:
%                      '', nothing written -- use this when ROUTE's basis
%                      keyword is a normal library name, e.g. '6-31g(d)').
%                      When non-empty, ROUTE is expected to already say
%                      'gen' or 'genecp' in place of a basis name (this
%                      function does not edit ROUTE itself). Typically
%                      built by G_MOLECULE_BUILDER from basis sets
%                      downloaded from Basis Set Exchange
%                      (basissetexchange.org), whose own 'gaussian94'
%                      output format is exactly this block's expected
%                      shape (basis functions per element, each ending in
%                      '****', then -- only if any element needs one -- a
%                      blank line followed by its ECP data).
%       'Comments'   - char or cellstr, free-form notes written as the
%                      very last thing in the file, each line prefixed
%                      with '! ' (a Gaussian comment marker, so they are
%                      never mistaken for additional input and are simply
%                      ignored by Gaussian itself) -- for documentation
%                      kept alongside the file, not read by Gaussian
%                      (default: '', nothing written).
%
%   The Gaussian input-file format does not differ between Gaussian 09 and
%   Gaussian 16, so (like G_READ_INPUT/G_SPECTRA_NM) this is a single
%   shared function rather than separate G09_/G16_ versions -- an
%   identical copy is kept in both the G09/ and G16/ folders.
%
%   Writes the same text layout G16_RESTART produces (a dash-bounded,
%   72-char word-wrapped route section; '%-4s   %14.8f  %14.8f  %14.8f'
%   Cartesian geometry lines), so the result round-trips through
%   G_READ_INPUT. Factored out of G16_RESTART's own inline writing block
%   so new code (currently: G_MOLECULE_BUILDER) can write a .gjf from
%   scratch without duplicating it; G16_RESTART/G09_RESTART are not
%   refactored to call this in this change, to avoid touching
%   already-shipped, working code for a DRY-only benefit -- a natural
%   follow-up, not done here.
%
%   Example:
%       G_write_gjf('water.gjf', {'O';'H';'H'}, ...
%           [0 0 0; 0.96 0 0; -0.24 0.93 0], ...
%           '# opt freq b3lyp/6-31g(d)', 0, 1, 'Title', 'Water');
%
%   See also G_READ_INPUT, G16_RESTART, G09_RESTART, G_MOLECULE_BUILDER.
%
%   Author: Sebastiano Trusso, CNR - Istituto per i Processi Chimico-Fisici (IPCF), Messina, Italy
%   Email: sebastiano.trusso@cnr.it
%   Developed with the assistance of an AI coding tool (Claude, Anthropic), under the author's supervision and review.

    p = inputParser;
    addRequired(p,  'outFile', @ischar);
    addRequired(p,  'symbols');
    addRequired(p,  'xyz',     @isnumeric);
    addRequired(p,  'route',   @ischar);
    addRequired(p,  'charge',  @isnumeric);
    addRequired(p,  'mult',    @isnumeric);
    addParameter(p, 'Title', 'Generated by G_write_gjf', @ischar);
    addParameter(p, 'Chk',   '', @ischar);
    addParameter(p, 'Mem',   '', @ischar);
    addParameter(p, 'Nproc', 0,  @isnumeric);
    addParameter(p, 'BasisBlock', '', @ischar);
    addParameter(p, 'Comments', '', @(x) ischar(x) || iscellstr(x) || isstring(x));
    parse(p, outFile, symbols, xyz, route, charge, mult, varargin{:});

    symbols = cellstr(symbols(:));
    Natoms  = numel(symbols);
    if size(xyz, 1) ~= Natoms
        error('G_write_gjf:sizeMismatch', ...
            'Number of symbols (%d) does not match number of xyz rows (%d).', Natoms, size(xyz, 1));
    end

    fid = fopen(outFile, 'w');
    if fid < 0
        error('G_write_gjf:cannotCreate', 'Cannot create output file: %s', outFile);
    end

    if ~isempty(p.Results.Chk),   fprintf(fid, '%%chk=%s\n',         p.Results.Chk);   end
    if p.Results.Nproc > 0,       fprintf(fid, '%%nprocshared=%d\n', p.Results.Nproc); end
    if ~isempty(p.Results.Mem),   fprintf(fid, '%%mem=%s\n',         p.Results.Mem);   end

    % Wrap route at 72 chars; see G16_restart.m's own WRAP_ROUTE for why a
    % trailing space (not an inserted one) marks a genuine word boundary.
    wrapped = wrap_route(strtrim(route), 72);
    fprintf(fid, '%s\n', repmat('-', 1, 70));
    for i = 1:numel(wrapped)
        if i < numel(wrapped)
            fprintf(fid, ' %s \n', wrapped{i});
        else
            fprintf(fid, ' %s\n', wrapped{i});
        end
    end
    fprintf(fid, '%s\n', repmat('-', 1, 70));

    fprintf(fid, '\n%s\n\n', p.Results.Title);
    fprintf(fid, '%d %d\n', charge, mult);
    for i = 1:Natoms
        fprintf(fid, '%-4s   %14.8f  %14.8f  %14.8f\n', symbols{i}, xyz(i,1), xyz(i,2), xyz(i,3));
    end
    fprintf(fid, '\n');

    if ~isempty(p.Results.BasisBlock)
        fprintf(fid, '%s\n\n', strtrim(p.Results.BasisBlock));
    end

    comments = cellstr(p.Results.Comments);
    comments = comments(~cellfun(@(l) isempty(strtrim(l)), comments));
    if ~isempty(comments)
        for i = 1:numel(comments)
            fprintf(fid, '! %s\n', comments{i});
        end
    end

    fclose(fid);
end

% -------------------------------------------------------------------------
function wrapped = wrap_route(route_str, max_len)
    tokens  = strsplit(route_str);
    wrapped = {};
    current = '';
    for i = 1:numel(tokens)
        tok = tokens{i};
        if isempty(tok), continue; end
        if isempty(current), current = tok;
        elseif numel(current)+1+numel(tok) <= max_len, current = [current, ' ', tok]; %#ok<AGROW>
        else, wrapped{end+1} = current; current = tok; %#ok<AGROW>
        end
    end
    if ~isempty(current), wrapped{end+1} = current; end
    if isempty(wrapped), wrapped = {route_str}; end
end
